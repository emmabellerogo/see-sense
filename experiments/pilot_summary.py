"""Summarise pilot JSONL files (validation-only runs from experiments/pilot.py) into a markdown report.

    python -m experiments.pilot_summary <out.md> <label=file.jsonl> [<label=file.jsonl> ...]

Reports measured seconds per epoch per variant and the training / validation curves' end points. Nothing
here touches test data: pilot records contain none.
"""
from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path


def load(path: str) -> list[dict]:
    recs = [json.loads(l) for l in Path(path).read_text().splitlines() if l.strip()]
    assert all(r.get("uses_test_data") is False for r in recs), "pilot records must not use test data"
    return recs


def main(out: str, specs: list[str]) -> None:
    lines = ["# Fashion-MNIST runtime pilot (training + validation only; no test data)", "",
             "Generated by `python -m experiments.pilot_summary`. Every number below comes from the JSONL files in this folder.", ""]
    for spec in specs:
        label, path = spec.split("=", 1)
        recs = load(path)
        lines += [f"## {label}", "", f"File: `{Path(path).name}`; {len(recs)} variant-runs; "
                  f"epochs {recs[0]['epochs']}, batch {recs[0]['batch_size']}, lr {recs[0]['lr']}, "
                  f"{recs[0]['n_train']} train / {recs[0]['n_val']} validation images, torch threads {recs[0]['torch_threads']}.", "",
                  "| Variant | seed | s/epoch (mean) | s/epoch (min–max) | final train loss | final val loss | final train acc | final val acc | best val-loss epoch |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r in recs:
            e = r["epoch_seconds"]
            lines.append(f"| {r['variant']} | {r['train_seed']} | {st.mean(e):.1f} | {min(e):.1f}–{max(e):.1f} | {r['train_loss'][-1]:.4f} | "
                         f"{r['val_loss'][-1]:.4f} | {r['train_accuracy'][-1]:.4f} | {r['val_accuracy'][-1]:.4f} | {r['best_epoch'] + 1} |")
        allsec = [s for r in recs for s in r["epoch_seconds"]]
        lines += ["", f"Mean over all epochs in this file: **{st.mean(allsec):.1f} s/epoch** (n = {len(allsec)}).", ""]
    Path(out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
